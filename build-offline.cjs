/**
 * Dependency-free build of the BEWNHS frontend into a classic browser script.
 * A classic script is intentional: browsers block ES module imports from file://.
 * Use `node build-offline.cjs` after making changes to the source modules.
 */
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const sequence = ['config.js', 'content.js', 'results.js', 'demo.js', 'api.js', 'app.js'];
const imports = /^\s*import\s+\{[^}]+\}\s+from\s+['"]\.\/[a-z-]+\.js['"];?\s*$/gm;
const exportDecls = /^export\s+(?=(?:const|let|var|function|async\s+function|class)\b)/gm;
const sources = sequence.map(name => {
  const source = fs.readFileSync(path.join(root, 'js', name), 'utf8');
  const noImports = source.replace(imports, '');
  if (/^\s*import\s|^\s*export\s/m.test(noImports.replace(exportDecls, ''))) {
    throw new Error(`Unexpected import/export syntax in ${name}; review build-offline.cjs before bundling.`);
  }
  return `\n// ===== SOURCE: js/${name} =====\n` + noImports.replace(exportDecls, '');
});
const output = `/* BEWNHS classic browser bundle — generated by build-offline.cjs. */\n` +
  `(function () {\n'use strict';\n` + sources.join('\n') + `\n})();\n`;
const dest = path.join(root, 'js', 'app.bundle.js');
fs.writeFileSync(dest, output);
console.log(`Created ${path.relative(root, dest)} (${Buffer.byteLength(output)} bytes)`);
